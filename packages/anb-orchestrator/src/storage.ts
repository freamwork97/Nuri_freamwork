/**
 * ANB Local Storage & Export Engine
 * Stores tasks, events, and exports structured results with full provenance.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import type { TaskRecord, AgentEvent, ApprovalDecision } from '@anb/core';
import { redactObject, redactText } from '@anb/core';

export class LocalStorage {
  private baseDir: string;
  private tasksFile: string;
  private eventsDir: string;
  private exportsDir: string;

  constructor(workspaceDir: string) {
    this.baseDir = path.join(workspaceDir, '.anb-data');
    this.eventsDir = path.join(this.baseDir, 'events');
    this.exportsDir = path.join(this.baseDir, 'exports');
    this.tasksFile = path.join(this.baseDir, 'tasks.json');

    if (!fs.existsSync(this.baseDir)) fs.mkdirSync(this.baseDir, { recursive: true });
    if (!fs.existsSync(this.eventsDir)) fs.mkdirSync(this.eventsDir, { recursive: true });
    if (!fs.existsSync(this.exportsDir)) fs.mkdirSync(this.exportsDir, { recursive: true });
    if (!fs.existsSync(this.tasksFile)) fs.writeFileSync(this.tasksFile, JSON.stringify([]));
  }

  saveTask(task: TaskRecord) {
    const tasks = this.listTasks();
    const idx = tasks.findIndex(t => t.taskId === task.taskId);
    const safeTask = redactObject(task);
    if (idx >= 0) {
      tasks[idx] = safeTask;
    } else {
      tasks.push(safeTask);
    }
    fs.writeFileSync(this.tasksFile, JSON.stringify(tasks, null, 2));
  }

  getTask(taskId: string): TaskRecord | null {
    const tasks = this.listTasks();
    return tasks.find(t => t.taskId === taskId) || null;
  }

  listTasks(): TaskRecord[] {
    try {
      const data = fs.readFileSync(this.tasksFile, 'utf-8');
      return JSON.parse(data) as TaskRecord[];
    } catch {
      return [];
    }
  }

  appendEvent(taskId: string, event: AgentEvent) {
    const eventFile = path.join(this.eventsDir, `${taskId}.jsonl`);
    const line = JSON.stringify(redactObject(event)) + '\n';
    fs.appendFileSync(eventFile, line, 'utf-8');
  }

  getEvents(taskId: string): AgentEvent[] {
    const eventFile = path.join(this.eventsDir, `${taskId}.jsonl`);
    if (!fs.existsSync(eventFile)) return [];
    const content = fs.readFileSync(eventFile, 'utf-8');
    return content
      .split('\n')
      .filter(l => l.trim().length > 0)
      .map(l => JSON.parse(l) as AgentEvent);
  }

  exportTaskResult(task: TaskRecord, summary: string, sourceUrls: string[] = []): { mdPath: string; jsonPath: string } {
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    const safePrompt = task.prompt.slice(0, 30).replace(/[^a-zA-Z0-9가-힣]/g, '_');
    const filenamePrefix = `${task.taskId}_${safePrompt}_${timestamp}`;

    const mdPath = path.join(this.exportsDir, `${filenamePrefix}.md`);
    const jsonPath = path.join(this.exportsDir, `${filenamePrefix}.json`);

    // Structured Markdown Export
    const mdContent = `# Nuri - 작업 결과 보고서

- **작업 ID:** \`${task.taskId}\`
- **실행 모델:** \`${task.model}\` (\`${task.providerId}\`)
- **생성 시각:** ${task.createdAt}
- **완료 시각:** ${task.completedAt || new Date().toISOString()}
- **작업 상태:** \`${task.state}\`

---

## 1. 사용자 프롬프트
> ${redactText(task.prompt)}

---

## 2. 작업 결과 요약
${redactText(summary)}

---

## 3. 참조 출처 및 증거 (Evidence Provenance)
${sourceUrls.length > 0 ? sourceUrls.map(u => `- [${u}](${u})`).join('\n') : '- 출처 URL 없음'}

---
*Generated by Nuri  with Official Subscription CLI*
`;

    fs.writeFileSync(mdPath, mdContent, 'utf-8');

    // Structured JSON Export
    const jsonContent = {
      taskId: task.taskId,
      providerId: task.providerId,
      model: task.model,
      prompt: redactText(task.prompt),
      state: task.state,
      summary: redactText(summary),
      sourceUrls,
      createdAt: task.createdAt,
      completedAt: task.completedAt || new Date().toISOString()
    };
    fs.writeFileSync(jsonPath, JSON.stringify(jsonContent, null, 2), 'utf-8');

    return { mdPath, jsonPath };
  }
}
